"""LLM 问答判断的提示词。

提示词集中放在这里，不内嵌在业务代码里：改词不用碰逻辑，
也能一眼看清「模型到底被要求做什么」。

这个提示词对应的是 **LLM 后端**（四档：是 / 否 / 是也不是 / 不重要），
与 Jev 后端的三档（是 / 否 / 无关）不是同一套口径，见 ``prompts.jev``。
"""

# 系统提示：约束输出只能是四档之一
JUDGE_SYSTEM_PROMPT = (
    '你是一个海龟汤推理游戏的助手。你必须严格按照游戏规则回答，'
    '只能回答"是"、"否"、"不重要"或"是也不是"，不能添加任何其他内容。'
)

# 模型允许返回的四档
VALID_RESPONSES = ("是", "否", "是也不是", "不重要")


def build_judge_prompt(question: str, true_answer: str) -> str:
    """构造问答判断的用户提示词。"""
    return (
        f"海龟汤游戏规则：\n"
        f"1. 故事的完整真相是：{true_answer}\n"
        f'2. 玩家提问或陈述："{question}"\n'
        f"3. 你的任务是判断玩家的说法是否符合真相。\n"
        f"4. 只能回答：\"是\"、\"否\"、\"不重要\"或\"是也不是\"。\n\n"
        f"判定标准：\n"
        f"- \"是\"：\n"
        f"  玩家命中关键事实或行为，且该信息能直接帮助接近真相。缺少部分细节可以忽略，只要不影响推理方向，就判\"是\"。\n"
        f"- \"否\"：\n"
        f"  与真相完全不符，或包含明显错误，会使玩家推理走向错误方向。\n"
        f"- \"不重要\"：\n"
        f"  与故事真相无关，或该信息无法推动推理进展。\n"
        f"- \"是也不是\"：\n"
        f"  玩家命中部分事实，但：\n"
        f"    1) 因果关系不完整或存在偏差；\n"
        f"    2) 表述中包含可能让玩家推理错误的成分；\n"
        f"    3) 忽略了与当前描述直接相关的重要关键点。\n"
        f"  如果只是缺少背景信息，但不影响方向，优先判\"是\"而不是\"是也不是\"。\n\n"
        f"额外说明：\n"
        f"- 不要求玩家一次性说出全部真相。\n"
        f"- 允许玩家只描述真相的一部分，只要方向正确且不会误导，就判\"是\"。\n"
        f"- 对可能误导玩家的陈述要谨慎，宁可判\"是也不是\"。\n"
        f"- 判定时平衡游戏流畅性和推理挑战性。"
    )
